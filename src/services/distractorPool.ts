function detectCategory(russianText: string): 'verbs' | 'nouns' | 'adjectives' | 'adverbs' | 'general' {
  const text = russianText.toLowerCase().trim();
  
  if (/([тч]ь|ти|ться|тись)$/.test(text)) {
    return 'verbs';
  }
  if (/(ый|ий|ой|ая|яя|ое|ее|ые|ие)$/.test(text)) {
    return 'adjectives';
  }
  if (/(о|е|ом|ем|жды)$/.test(text) || text.startsWith('за ') || text.startsWith('по-')) {
    return 'adverbs';
  }
  return 'nouns';
}

export function getSmartFallbackDistractors(targetRussian: string, count: number = 6, englishWord?: string): string[] {
  // Check if we have tailored deceptive distractors
  if (englishWord) {
    const specific = SPECIFIC_DECEPTIVE_DISTRACTORS[englishWord.toLowerCase().trim()];
    if (specific && specific.length >= count) {
      return [...specific].sort(() => Math.random() - 0.5).slice(0, count);
    }
  }

  const category = detectCategory(targetRussian);
  const pool = SMART_DISTRACTOR_POOLS[category] || SMART_DISTRACTOR_POOLS.general;
  
  const cleanTarget = targetRussian.toLowerCase().trim();
  const available = pool.filter(w => w.toLowerCase() !== cleanTarget);
  
  const shuffled = [...available].sort(() => Math.random() - 0.5);
  
  if (shuffled.length < count) {
    const generalAvailable = SMART_DISTRACTOR_POOLS.general.filter(
      w => w.toLowerCase() !== cleanTarget && !shuffled.includes(w)
    );
    shuffled.push(...generalAvailable);
  }
  
  return shuffled.slice(0, count);
}
