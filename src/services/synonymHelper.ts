/**
 * Expand a Russian phrase with common aspectual, prepositional and grammatical pairs
 */
export function expandRussianGrammarVariants(text: string): string[] {
  const results = new Set<string>();
  const clean = text.trim();
  if (!clean) return [];

  results.add(clean);

  // Common verb aspect pairs (совершенный / несовершенный вид)
  const verbPairs: [RegExp, string][] = [
    [/^извиняться/, 'извиниться'],
    [/^извиниться/, 'извиняться'],
    [/^сломаться/, 'ломаться'],
    [/^ломаться/, 'сломаться'],
    [/^преуспеть/, 'преуспевать'],
    [/^преуспевать/, 'преуспеть'],
    [/^добиться/, 'добиваться'],
    [/^добиваться/, 'добиться'],
    [/^выяснить/, 'выяснять'],
    [/^выяснять/, 'выяснить'],
    [/^узнать/, 'узнавать'],
    [/^узнавать/, 'узнать'],
    [/^надеть/, 'надевать'],
    [/^надевать/, 'надеть'],
    [/^воспитать/, 'воспитывать'],
    [/^воспитывать/, 'воспитать'],
    [/^поднять/, 'поднимать'],
    [/^поднимать/, 'поднять'],
    [/^достичь/, 'достигать'],
    [/^достигать/, 'достичь'],
  ];

  for (const [pattern, replacement] of verbPairs) {
    if (pattern.test(clean)) {
      results.add(clean.replace(pattern, replacement));
    }
  }

  // Prepositional variants
  if (clean === 'за границей' || clean === 'заграницей') {
    results.add('за границей');
    results.add('за границу');
    results.add('за рубежом');
    results.add('за рубеж');
  }

  return Array.from(results);
}
